"""Phase 0a: wild cluster bootstrap-t on the tail specifications.

Why this exists. The Stage 3 gate reports cluster-robust standard errors. The
CRVE is asymptotic in the number of CLUSTERS, not observations, and is biased
downward below roughly 40-50 of them. The top-decile specification has 35. Its
reported upper bound of 2.14pp sits against a 2.38pp break-even, so the whole
"excluded" claim rests on an SE estimator working outside its comfortable range
-- exactly where it under-reports.

The remedy is the wild cluster bootstrap-t with the null imposed (WCR), which
Cameron, Gelbach & Miller (2008) show controls size with few clusters where the
CRVE does not. Rademacher weights, 9,999 replications, confidence intervals by
test inversion rather than by beta +/- c*se, following Roodman, MacKinnon,
Nielsen & Webb (2019).

This script also closes a reproducibility gap: the two tail specifications
appear in the writeup but in none of the committed scripts, so they could not be
re-run. They are defined here.

    python scripts/phase0_wildboot.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.api as sm

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from stage3_gate_game import build  # noqa: E402

B_REPS = 9_999
ALPHA = 0.05
SEED = 20260907
SIGMA_GAME = 15.51    # measured in build_games.py
PHI_DENSITY = 0.3989  # standard normal density at zero
BREAK_EVEN_PP = 2.38  # -110 both sides


def crve(X: np.ndarray, y: np.ndarray, g: np.ndarray):
    """OLS with one-way cluster-robust covariance and the usual correction."""
    XtXi = np.linalg.inv(X.T @ X)
    beta = XtXi @ (X.T @ y)
    e = y - X @ beta
    n, k = X.shape
    uniq = np.unique(g)
    meat = np.zeros((k, k))
    for cl in uniq:
        m = g == cl
        s = X[m].T @ e[m]
        meat += np.outer(s, s)
    c = len(uniq) / (len(uniq) - 1) * (n - 1) / (n - k)
    return beta, XtXi @ (c * meat) @ XtXi


def _boot_t(X, y, x_idx, beta0, W, XtXi, cluster_rows, corr):
    """Studentised bootstrap statistics under H0: beta[x_idx] == beta0.

    The null is imposed before resampling (WCR): the restricted residuals are
    what gets sign-flipped, so the bootstrap distribution is generated by a
    process in which the null is true.
    """
    n, k = X.shape
    x = X[:, x_idx]
    Xr = np.delete(X, x_idx, axis=1)
    yr = y - beta0 * x
    br = np.linalg.lstsq(Xr, yr, rcond=None)[0]
    e_r = yr - Xr @ br
    fitted = Xr @ br + beta0 * x

    Ystar = fitted[:, None] + e_r[:, None] * W       # (n, B)
    Bhat = XtXi @ (X.T @ Ystar)                      # (k, B)
    Estar = Ystar - X @ Bhat

    meat = np.zeros((k, k, W.shape[1]))
    for rows in cluster_rows:
        S = X[rows].T @ Estar[rows]                  # (k, B)
        meat += S[:, None, :] * S[None, :, :]
    A = XtXi[x_idx]
    var = corr * np.einsum("i,ijb,j->b", A, meat, A)
    se = np.sqrt(np.maximum(var, 1e-300))
    return (Bhat[x_idx] - beta0) / se


def wild_cluster(df: pd.DataFrame, ycol: str, xcols: list[str],
                 cluster: str, x_of_interest: str,
                 b_reps: int = B_REPS, seed: int = SEED) -> dict:
    """WCR bootstrap-t p-value at zero plus an equal-tailed CI by inversion."""
    d = df[[ycol, cluster] + xcols].dropna()
    X = sm.add_constant(d[xcols].astype(float)).to_numpy()
    names = ["const"] + xcols
    x_idx = names.index(x_of_interest)
    y = d[ycol].to_numpy(float)
    g = pd.factorize(d[cluster])[0]

    beta, V = crve(X, y, g)
    b_hat, se_hat = beta[x_idx], float(np.sqrt(V[x_idx, x_idx]))

    n, k = X.shape
    G = len(np.unique(g))
    XtXi = np.linalg.inv(X.T @ X)
    cluster_rows = [np.flatnonzero(g == cl) for cl in np.unique(g)]
    corr = G / (G - 1) * (n - 1) / (n - k)

    # One fixed weight draw, reused at every candidate null, so the inverted
    # p-value function is smooth in beta0 and the endpoints are well defined.
    rng = np.random.default_rng(seed)
    W = rng.choice([-1.0, 1.0], size=(G, b_reps))[g]

    def pval(beta0: float) -> float:
        t_star = _boot_t(X, y, x_idx, beta0, W, XtXi, cluster_rows, corr)
        t_obs = (b_hat - beta0) / se_hat
        return (1.0 + np.sum(np.abs(t_star) >= abs(t_obs))) / (b_reps + 1.0)

    def endpoint(direction: int) -> float:
        """Walk out in half-SE steps until the test rejects, then bisect."""
        lo = hi = b_hat
        for step in range(1, 41):
            hi = b_hat + direction * step * 0.5 * se_hat
            if pval(hi) < ALPHA:
                break
            lo = hi
        else:
            return float("nan")
        for _ in range(30):
            mid = 0.5 * (lo + hi)
            if pval(mid) < ALPHA:
                hi = mid
            else:
                lo = mid
            if abs(hi - lo) < 1e-4 * max(1.0, se_hat):
                break
        return 0.5 * (lo + hi)

    return dict(n=n, clusters=G, beta=b_hat, se=se_hat,
                crve_lo=b_hat - 1.96 * se_hat, crve_hi=b_hat + 1.96 * se_hat,
                boot_p=pval(0.0), boot_lo=endpoint(-1), boot_hi=endpoint(+1))


def pp(points: float) -> float:
    """Points of margin -> percentage points of cover probability."""
    return PHI_DENSITY * points / SIGMA_GAME * 100.0


def specs() -> list[tuple[str, pd.DataFrame]]:
    """The four Test B specifications the writeup plots, tails included.

    The tail cut is on |distance| -- the team's own system distance, not the
    matchup contrast -- and the percentile is taken within the thesis window.
    That is the cut that reproduces the reported 35 clusters.

    |distance| is recovered as sqrt(-phi) rather than merged back from
    phi.parquet. The merge would be on (school, season), and that key is not
    unique there: nine team-seasons carry two rows, so a merge silently fans
    out 39 team-games. Deriving it from a column build() already carries keeps
    the sample exactly as published.
    """
    df = build()
    df["abs_distance"] = np.sqrt(np.clip(-df["phi_own"], 0, None))
    win = df[df.season.between(2022, 2025)]
    out = [("Test B, thesis 2022-25", win), ("Test B, long 2015-25", df)]
    for q in (75, 90):
        v = win["abs_distance"]
        out.append((f"|distance| > p{q}, thesis",
                    win[v > np.nanpercentile(v, q)]))
    return out


def validate(n_sims: int = 1_000, b_reps: int = 999,
             seed: int = SEED) -> None:
    """Size check: the premise of this correction, measured rather than cited.

    Simulate under the null on the real cluster structure of the top-decile
    specification -- 35 clusters, the same unbalanced sizes, a regressor
    constant within cluster as Phi is -- and count how often each test rejects
    a true null at a nominal 5%. If the CRVE is fine here there is nothing to
    correct, and this reports that instead.
    """
    _, tail = specs()[3]
    d = tail[["resid", "ts", "phi_diff"]].dropna()
    g = pd.factorize(d["ts"])[0]
    sizes = np.bincount(g)
    G = len(sizes)
    rng = np.random.default_rng(seed)

    crve_rej = boot_rej = 0
    for _ in range(n_sims):
        gi = np.repeat(np.arange(G), sizes)
        x = np.repeat(rng.normal(size=G), sizes)      # cluster-level regressor
        # Null holds: y is noise with a cluster component, unrelated to x.
        y = np.repeat(rng.normal(size=G), sizes) + rng.normal(size=len(gi))
        X = np.column_stack([np.ones(len(gi)), x])
        beta, V = crve(X, y, gi)
        se = np.sqrt(V[1, 1])
        crve_rej += abs(beta[1] / se) > 1.96

        n, k = X.shape
        XtXi = np.linalg.inv(X.T @ X)
        rows = [np.flatnonzero(gi == c) for c in range(G)]
        corr = G / (G - 1) * (n - 1) / (n - k)
        W = rng.choice([-1.0, 1.0], size=(G, b_reps))[gi]
        t_star = _boot_t(X, y, 1, 0.0, W, XtXi, rows, corr)
        p = (1.0 + np.sum(np.abs(t_star) >= abs(beta[1] / se))) / (b_reps + 1.0)
        boot_rej += p < 0.05

    print(f"size check under a true null, G={G} clusters, {n_sims} simulations,"
          f" nominal 5%")
    print(f"    CRVE t with normal critical values : "
          f"{crve_rej / n_sims * 100:5.1f}% rejection")
    print(f"    wild cluster bootstrap-t (WCR)     : "
          f"{boot_rej / n_sims * 100:5.1f}% rejection\n")


def main() -> None:
    if "--validate" in sys.argv:
        validate()
        return
    print(f"wild cluster bootstrap-t, Rademacher, B={B_REPS}, null imposed "
          f"(WCR), CI by test inversion at alpha={ALPHA}\n")
    hdr = (f"{'specification':<26}{'n':>6}{'G':>4}{'gamma':>8}"
           f"{'CRVE 95%':>19}{'bootstrap 95%':>19}{'boot p':>9}"
           f"{'CRVE pp':>9}{'boot pp':>9}")
    print(hdr)
    print("-" * len(hdr))
    rows = []
    for label, d in specs():
        r = wild_cluster(d, "resid", ["phi_diff"], "ts", "phi_diff")
        r["label"] = label
        rows.append(r)
        print(f"{label:<26}{r['n']:>6}{r['clusters']:>4}{r['beta']:>+8.3f}"
              f"   [{r['crve_lo']:+.2f}, {r['crve_hi']:+.2f}]"
              f"   [{r['boot_lo']:+.2f}, {r['boot_hi']:+.2f}]"
              f"{r['boot_p']:>9.3f}"
              f"{pp(r['crve_hi']):>9.2f}{pp(r['boot_hi']):>9.2f}")
    print("-" * len(hdr))
    print(f"break-even at -110 = {BREAK_EVEN_PP:.2f}pp;  "
          f"pp = {PHI_DENSITY} * points / {SIGMA_GAME}\n")
    for r in rows:
        widen = (r["boot_hi"] - r["boot_lo"]) / (r["crve_hi"] - r["crve_lo"])
        verdict = ("excludes break-even" if pp(r["boot_hi"]) < BREAK_EVEN_PP
                   else "UNDERPOWERED, interval crosses break-even")
        print(f"  {r['label']:<26} G={r['clusters']:<4} bootstrap CI is "
              f"{widen:.2f}x the CRVE width -> {verdict}")


if __name__ == "__main__":
    main()
